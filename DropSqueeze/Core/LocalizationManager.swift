// MARK: - Supported 10 Languages

public enum AppLanguage: String, CaseIterable, Identifiable {
    case zhHans = "zh-Hans"
    case zhHant = "zh-Hant"
    case en = "en"
    case ja = "ja"
    case ko = "ko"
    case de = "de"
    case fr = "fr"
    case esES = "es-ES"
    case it = "it"
    case ptBR = "pt-BR"

    public var id: String { rawValue }

    public var displayName: String {
        switch self {
        case .zhHans: return "简体中文"
        case .zhHant: return "繁體中文"
        case .en: return "English"
        case .ja: return "日本語"
        case .ko: return "한국어"
        case .de: return "Deutsch"
        case .fr: return "Français"
        case .esES: return "Español"
        case .it: return "Italiano"
        case .ptBR: return "Português (Brasil)"
        }
    }
}

// MARK: - Central Localization Manager

@MainActor
public final class LocalizationManager: ObservableObject {
    public static let shared = LocalizationManager()

    @Published public var currentLanguage: AppLanguage {
        didSet {
            UserDefaults.standard.set(currentLanguage.rawValue, forKey: "DropSqueeze.AppLanguage")
            updateBundle()
        }
    }

    private var currentBundle: Bundle?

    public init() {
        if let saved = UserDefaults.standard.string(forKey: "DropSqueeze.AppLanguage"),
           let lang = AppLanguage(rawValue: saved) {
            self.currentLanguage = lang
        } else {
            let pref = Locale.preferredLanguages.first ?? "zh-Hans"
            if pref.starts(with: "zh-Hant") || pref.starts(with: "zh-TW") || pref.starts(with: "zh-HK") {
                self.currentLanguage = .zhHant
            } else if pref.starts(with: "zh") {
                self.currentLanguage = .zhHans
            } else if pref.starts(with: "ja") {
                self.currentLanguage = .ja
            } else if pref.starts(with: "ko") {
                self.currentLanguage = .ko
            } else if pref.starts(with: "de") {
                self.currentLanguage = .de
            } else if pref.starts(with: "fr") {
                self.currentLanguage = .fr
            } else if pref.starts(with: "es") {
                self.currentLanguage = .esES
            } else if pref.starts(with: "it") {
                self.currentLanguage = .it
            } else if pref.starts(with: "pt") {
                self.currentLanguage = .ptBR
            } else {
                self.currentLanguage = .en
            }
        }
        updateBundle()
    }

    private func updateBundle() {
        let bundleClass = Bundle(for: LocalizationManager.self)
        if let path = bundleClass.path(forResource: currentLanguage.rawValue, ofType: "lproj"),
           let bundle = Bundle(path: path) {
            self.currentBundle = bundle
        } else if let path = Bundle.main.path(forResource: currentLanguage.rawValue, ofType: "lproj"),
                  let bundle = Bundle(path: path) {
            self.currentBundle = bundle
        } else {
            self.currentBundle = nil
        }
    }

    public func tr(_ key: String, _ args: CVarArg...) -> String {
        return tr(key, lang: currentLanguage, args: args)
    }

    public func tr(_ key: String, lang: AppLanguage, args: [CVarArg] = []) -> String {
        var format = LocalizedStringsTable.table[key]?[lang]
        if format == nil, let currentBundle {
            let localized = currentBundle.localizedString(forKey: key, value: nil, table: nil)
            if localized != key {
                format = localized
            }
        }
        let template = format ?? LocalizedStringsTable.table[key]?[.en] ?? LocalizedStringsTable.table[key]?[.zhHans] ?? key
        if args.isEmpty {
            return template
        }
        return String(format: template, arguments: args)
    }
}

// MARK: - Global Convenience Helper

public enum L10n {
    @MainActor
    public static func tr(_ key: String, _ args: CVarArg...) -> String {
        return LocalizationManager.shared.tr(key, lang: LocalizationManager.shared.currentLanguage, args: args)
    }

    @MainActor
    public static func tr(_ key: String, lang: AppLanguage, _ args: CVarArg...) -> String {
        return LocalizationManager.shared.tr(key, lang: lang, args: args)
    }
}

